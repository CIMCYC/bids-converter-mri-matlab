function cfg = generate_bids_filename(cfg, dcm)
%% Generate empty parameters:
data_type = char();
data_modality = char();
task_name = char();
run_number = char();
events_filename = char();
context_filename = char();
direction = char();
echo = char();
acquisition = char();
reconstruction = char();
part = char();

%% Extract data information:
if isfield(dcm, 'data_type')
    data_type  = dcm.data_type;
end

if isfield(dcm, 'modality')
    data_modality  = dcm.modality;
end

if isfield(dcm, 'task')
    task_name  = ['task-' dcm.task];
end

if isfield(dcm, 'run')
    run_number  = ['run-' dcm.run];
end

if isfield(dcm, 'dir')
    direction  = ['dir-' dcm.dir];
end

if isfield(dcm, 'echo')
    echo  = ['echo-' dcm.echo];
end

if isfield(dcm, 'acquisition')
    acquisition  = ['acq-' dcm.acquisition];
end

if isfield(dcm, 'reconstruction')
    reconstruction  = ['rec-' dcm.reconstruction];
end

if isfield(dcm, 'part')
    part  = ['part-' dcm.part];
end


%% Generate the file depending on dataType name:
% The BIDS standard defines a file naming structure that depends on the
% data type. We break down the modalities currently available in the
% tool.
% Note: When introducing a new parameter, check the order in which it
% must appear for each of the modalities.

if strcmp(data_type,'func')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        task_name '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        direction '_' ...
        run_number '_' ...
        echo '_' ...
        part '_'...
        data_modality];

    events_filename = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        task_name '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        direction '_' ...
        run_number '_' ...
        'events.tsv'];

elseif strcmp(data_type,'anat')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        task_name '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        run_number '_' ...
        echo '_' ...
        part '_'...
        data_modality];

elseif strcmp(data_type,'fmap')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        acquisition '_' ...
        direction '_' ...
        run_number '_' ...
        echo];

elseif strcmp(data_type,'dwi')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        direction '_' ...
        run_number '_' ...
        part '_'...
        data_modality];

elseif strcmp(data_type,'mrs')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        task_name '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        run_number '_' ...
        echo '_' ...
        data_modality];

elseif strcmp(data_type,'perf')

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        direction '_' ...
        run_number '_' ...
        echo '_' ...
        part '_'...
        data_modality];

    context_filename = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        acquisition '_' ...
        reconstruction '_' ...
        direction '_' ...
        run_number '_' ...
        '_aslcontext.tsv'];

else

    file_name = [...
        cfg.subject_id '_' ...
        cfg.session_id '_' ...
        data_modality];

end

%% Delete duplicate caracters:
cfg.file_name = remove_duplicate_char(file_name,'_');
cfg.events_filename = remove_duplicate_char(events_filename,'_');
cfg.context_filename = remove_duplicate_char(context_filename,'_');

end